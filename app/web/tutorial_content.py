def _nav_click_step(step_id: str, track: str, labels: list[str], highlight: str, caption: str) -> dict:
    """A bridge screen: the nav bar with exactly one item clickable.

    Inserted before a section's first content step so a viewer sees where a
    page came from instead of landing on it out of nowhere.
    """
