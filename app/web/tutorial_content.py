"""Content for the interactive tutorial (`/tutorial`, `tutorial/offline.html`).

Additive, non-core feature: it never calls `app.services`, never touches the
database, and is not part of the spec §12 acceptance suite. Every "click" in
the tutorial advances a scripted step; nothing here executes a real booking,
preemption, invitation, or deletion.

`TUTORIAL_STEPS` is the single source of truth for content, shared by both
delivery modes (the served `/tutorial` page and the standalone
`tutorial/offline.html` file generated by `manage.py tutorial-build`). Real
UI copy is always pulled from `app.i18n.en`'s catalogue -- via the `*_key`
convention in `_resolve()` for the handful of fields reused across many
steps (form field labels, notices, legends), or via `_t()` inline for
everything else -- so a renamed string key breaks loudly here instead of
silently drifting from the real screens it mirrors. Illustrative sample data
(names, times, room contents) is authored directly since it has no real
counterpart to drift from.

Each demo section that is reached by clicking somewhere in the site's
navigation opens with a `nav_click` bridge step (see `_nav_click_step()`)
that shows exactly which nav item was clicked to get there, before diving
into that section's content -- a step landing on a screen "out of nowhere"
was confusing to follow.
"""

from __future__ import annotations

from app.i18n.en import STRINGS as _EN

TRACKS = ("member", "admin")


def _text(key: str) -> str:
    return _EN[key]


def _t(key: str, **params: object) -> str:
    """Resolve an `app.i18n.en` string, formatting it if params are given."""
    text = _EN[key]
    return text.format(**params) if params else text


def _resolve(step: dict) -> dict:
    data = step["screen_data"]
    resolved = dict(data)
    if "fields" in data:
        fields = []
        for f in data["fields"]:
            field = {"label": _text(f["key"]), "type": f.get("type", "text")}
            if "value" in f:
                field["value"] = f["value"]
            if "help_key" in f:
                field["help"] = _text(f["help_key"])
            fields.append(field)
        resolved["fields"] = fields
    if "submit_key" in data:
        resolved["submit_label"] = _text(data["submit_key"])
    if "message_key" in data:
        resolved["message"] = _text(data["message_key"])
    if "banner_key" in data:
        resolved["banner"] = _text(data["banner_key"])
    if "notice_key" in data:
        resolved["notice"] = _text(data["notice_key"])
    if "legend" in data:
        resolved["legend"] = [_text(k) for k in data["legend"]]
    return {**step, "screen_data": resolved}


